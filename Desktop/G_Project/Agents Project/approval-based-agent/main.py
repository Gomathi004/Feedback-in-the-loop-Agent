from pathlib import Path
from datetime import datetime

BASE_DIR = Path(__file__).resolve().parent
WORKSPACE = BASE_DIR / "workspace"


def build_content(request: str) -> tuple[str, str, str]:
    """
    Rule-based proposal builder.
    This uses ordinary Python templates, not an AI model.
    Returns (action, filename, content).
    """
    text = request.strip()
    lower = text.lower()

    # Try to identify a requested .txt filename.
    words = text.replace('"', " ").replace("'", " ").split()
    filename = next(
        (word.strip(".,:;!?()[]{}") for word in words
         if word.lower().endswith(".txt")),
        "task_notes.txt",
    )

    # Only accept a simple filename; never accept a path from user input.
    if (
        Path(filename).name != filename
        or "/" in filename
        or "\\" in filename
        or ".." in filename
        or ":" in filename
    ):
        raise ValueError("Please use a simple filename such as notes.txt.")

    if any(word in lower for word in ("machine learning", " ml ", "ml.txt")):
        content = """MACHINE LEARNING STUDY NOTES
Generated by a Python template (not an AI model)

1. Introduction
Machine learning is a field of computing where programs learn patterns from examples
and use those patterns to make predictions or decisions.

2. Main types
- Supervised learning: learns from labelled examples.
- Unsupervised learning: finds patterns in unlabelled data.
- Reinforcement learning: learns through actions, feedback, and rewards.

3. Common algorithms
- Linear Regression: predicts a numeric value.
- Logistic Regression: commonly used for classification.
- Decision Tree: makes predictions using a sequence of rules.
- K-Means: groups similar data points into clusters.

4. Real-world applications
Machine learning is used in spam filtering, recommendation systems, fraud detection,
image recognition, forecasting, and speech recognition.

5. Advantages
- Can find patterns in large datasets.
- Can automate some prediction tasks.
- Can improve when trained with suitable data.

6. Limitations
- Needs suitable data and testing.
- Can reproduce bias in training data.
- Predictions may be inaccurate when real-world conditions change.

7. Summary
Choose an algorithm based on the problem, check data quality, evaluate performance,
and monitor the model after deployment.
"""
    elif "agenda" in lower or "meeting" in lower:
        content = """MEETING AGENDA
Generated by a Python template (not an AI model)

Date: ____________________
Time: ____________________
Participants: ______________

1. Introduction and meeting objective
2. Review of previous action items
3. Project updates and progress
4. Challenges, blockers, and risks
5. Decisions required
6. Next steps, owners, and deadlines
7. Questions and closing

Notes:
__________________________________________________
__________________________________________________
"""
    elif "todo" in lower or "to-do" in lower or "task list" in lower:
        content = """TASK LIST
Generated by a Python template (not an AI model)

[ ] Task 1:
    Owner:
    Due date:

[ ] Task 2:
    Owner:
    Due date:

[ ] Task 3:
    Owner:
    Due date:

Notes:
__________________________________________________
"""
    else:
        content = f"""TASK NOTES
Generated by a Python template (not an AI model)

Original request:
{text}

Objective:
Record the goal and expected outcome for this task.

Steps:
1. Clarify the requirements.
2. Complete the work.
3. Review the result.
4. Record the next steps.

Created proposal at: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}
"""
    return "create_file", filename, content


def execute_approved_action(filename: str, content: str) -> Path:
    """Create a new .txt file directly in workspace; never overwrite."""
    WORKSPACE.mkdir(exist_ok=True)
    target = WORKSPACE / filename

    if target.parent.resolve() != WORKSPACE.resolve():
        raise ValueError("Files can only be created directly inside workspace.")
    if target.suffix.lower() != ".txt":
        raise ValueError("Only .txt files are allowed.")

    # Exclusive mode fails safely if the file already exists.
    with target.open("x", encoding="utf-8") as file:
        file.write(content)

    return target


def main():
    WORKSPACE.mkdir(exist_ok=True)
    print("=" * 56)
    print(" PYTHON-ONLY APPROVAL-BASED AGENT")
    print(" No API key | No AI model | No database | No UI")
    print("=" * 56)
    print("This demo uses predefined Python templates.")
    print("Allowed action: create a new .txt file in workspace/.")
    print("Type 'exit' to quit.\n")

    while True:
        request = input("Enter your task: ").strip()

        if request.lower() in {"exit", "quit"}:
            print("Goodbye!")
            break
        if not request:
            print("Please enter a task.")
            continue

        try:
            action, filename, content = build_content(request)
        except ValueError as exc:
            print(f"Could not prepare proposal: {exc}")
            continue

        print("\n" + "-" * 56)
        print("PROPOSED ACTION — NOT EXECUTED")
        print(f"Action: {action}")
        print(f"Target: workspace/{filename}")
        print("\nContent for review:\n")
        print(content)
        print("-" * 56)

        decision = input("Approve and execute? Type 'yes' or 'no': ").strip().lower()

        if decision == "yes":
            try:
                created_path = execute_approved_action(filename, content)
                print(f"APPROVED: File created at {created_path}\n")
            except FileExistsError:
                print("Execution blocked: that file already exists. Nothing overwritten.\n")
            except Exception as exc:
                print(f"Execution failed: {exc}\n")
        else:
            print("REJECTED: No file was created.\n")


if __name__ == "__main__":
    main()
